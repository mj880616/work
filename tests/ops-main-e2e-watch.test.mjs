const run = (id, conclusion, created, extra = {}) => ({id, conclusion, created_at: created, head_branch: 'main', event: 'push', ...extra});

test('실패 → 이슈 열기, 이미 열려 있으면 댓글만, 초록 → 닫기, 옛 실행·취소·PR은 아무것도 안 함', () => {
  const r1 = run(1, 'failure', '2026-11-27T01:00:00Z');
  assert.deepEqual(decide({run: r1, runs: [r1], openIssue: null}), {action: 'open', issue: null});
  assert.deepEqual(decide({run: r1, runs: [r1], openIssue: 7}), {action: 'comment', issue: 7});
  const r2 = run(2, 'success', '2026-11-27T02:00:00Z');
  assert.deepEqual(decide({run: r2, runs: [r2, r1], openIssue: 7}), {action: 'close', issue: 7});
  assert.equal(decide({run: r2, runs: [r2], openIssue: null}).action, 'none');
  // 뒤늦게 끝난 옛 실패는 더 새 초록을 덮지 않는다.
  assert.equal(decide({run: r1, runs: [r2, r1], openIssue: null}).action, 'none');
  // 더 새 실행이 취소됐으면 판정에 쓰지 않는다.
  assert.equal(decide({run: r1, runs: [run(3, 'cancelled', '2026-11-27T03:00:00Z'), r1], openIssue: null}).action, 'open');
  assert.equal(decide({run: run(4, 'cancelled', '2026-11-27T04:00:00Z'), runs: [], openIssue: 7}).action, 'none');
  assert.equal(decide({run: run(5, 'failure', '2026-11-27T05:00:00Z', {event: 'pull_request'}), runs: [], openIssue: null}).action, 'none');
  assert.equal(decide({run: run(6, 'failure', '2026-11-27T06:00:00Z', {head_branch: 'x'}), runs: [], openIssue: null}).action, 'none');
  assert.equal(decide({run: run(7, 'failure', '2026-11-27T07:00:00Z', {event: 'schedule'}), runs: [], openIssue: null}).action, 'open');
});

test('이슈 글: 실행 번호·SHA·실패 위치와 merge 멈춤 규칙, 꼬리말', () => {
  const r = {run_number: 9, html_url: 'https://github.com/mj880616/work/actions/runs/1', event: 'push', head_sha: 'a'.repeat(40)};
  const body = failureBody({run: r, failed: ['tests/app-e2e/x.spec.mjs:1:2'], jobs: ['browser-e2e-shard (1/24)']});
  assert.match(body, /\[#9\]\(https:\/\/github\.com\/mj880616\/work\/actions\/runs\/1\)/);
  assert.match(body, /`a{40}`/);
  assert.match(body, /`tests\/app-e2e\/x\.spec\.mjs:1:2`/);
  assert.match(body, /merge를 멈추고/);
  assert.match(body, /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\n$/);
  assert.match(failureBody({run: r, failed: [], jobs: ['startup-benchmark']}), /실패한 job: `startup-benchmark`/);
  assert.match(successBody({run: r}), /다시 초록/);
  assert.equal(ISSUE_TITLE, 'main 시험 깨짐');
});

test('main-e2e-watch.yml: App browser E2E check가 main에서 끝날 때만, 권한은 읽기 + issues: write, 비밀값 없음, 고정 SHA, PR 코드 안 받음', () => {
  const src = readFileSync(new URL('../.github/workflows/main-e2e-watch.yml', import.meta.url), 'utf8');
  const on = src.slice(src.indexOf('\non:\n'), src.indexOf('\npermissions:'));
  assert.match(on, /^  workflow_run:\n    workflows: \['App browser E2E check'\]\n    types: \[completed\]\n    branches: \[main\]\n$/m);
  assert.doesNotMatch(on, /pull_request|push:|schedule:|workflow_dispatch/);
  assert.doesNotMatch(src, /pull_request_target|secrets\.|head_sha\s*}}|workflow_run\.head_sha/);
  const perms = [...src.matchAll(/^\s+(contents|actions|issues|pull-requests|id-token|checks|statuses|deployments|packages|pages):\s*(\w+)\s*$/gm)].map(m => `${m[1]}:${m[2]}`);
  assert.deepEqual(perms, ['contents:read', 'actions:read', 'issues:write']);
  for (const use of src.matchAll(/uses:\s*(\S+)/g)) assert.match(use[1], /@[0-9a-f]{40}$/, use[1]);
  assert.match(src, /ref: main\n\s+persist-credentials: false/);
  assert.match(src, /github\.event\.workflow_run\.head_branch == 'main'/);
  assert.match(src, /node scripts\/ops\/main-e2e-watch\.mjs --run "\$RUN_ID"/);
  // 앱 시험 workflow 이름이 바뀌면 이 감시가 조용히 멈추므로 함께 지킨다.
  assert.match(readFileSync(new URL('../.github/workflows/app-e2e-check.yml', import.meta.url), 'utf8'), /^name: App browser E2E check$/m);
});
