#!/usr/bin/env node
// main 시험 깨짐 감시 (OPS-main깨짐감시, 2026-11-27 사용자 결정).
// main의 'App browser E2E check'(push·밤 정기 실행)가 끝날 때마다(.github/workflows/main-e2e-watch.yml) 돈다.
//   - main에서 가장 최근에 끝난 그 시험이 실패면: 'main 시험 깨짐' 이슈를 열거나(없으면) 열린 이슈에 댓글을 단다.
//   - 가장 최근에 끝난 시험이 성공이면: 열린 이슈에 댓글을 달고 닫는다.
//   - 끝난 실행이 가장 최근 것이 아니면(늦게 끝난 옛 커밋) 아무것도 하지 않는다 — 더 새 실행이 상태를 정한다.
// 이슈 글에는 실행 번호·SHA·실패한 시험 파일:줄만 쓴다(시험 제목·로그 원문·비밀값·개인정보 없음).
//
//   node scripts/ops/main-e2e-watch.mjs --run <run_id> [--repo owner/name] [--dry-run]
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

export const WORKFLOW = 'app-e2e-check.yml';
export const TITLE = 'main 시험 깨짐';
export const EVENTS = new Set(['push', 'schedule']);
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';

// 줄 앞 시각과 터미널 제어 글자(line 보고기의 '\x1b[1A\x1b[2K' 등)를 뗀다.
const clean = line => line.replace(/^\d{4}-\d\d-\d\dT[\d:.]+Z\s?/, '').replace(/\x1b\[[0-9;]*[A-Za-z]/g, '').replace(/^##\[\w+\]/, '').replace(/\r$/, '');

// Playwright 끝 요약의 'N failed' 아래 줄들에서 시험 파일:줄만 뽑는다(flaky·did not run 줄은 뺀다).
export function failedSpecsFromLog(text) {
  const out = new Set();
  let inFailed = false;
  for (const raw of String(text).split('\n')) {
    const line = clean(raw);
    if (/^\s+\d+ failed\s*$/.test(line)) { inFailed = true; continue; }
    if (!inFailed) continue;
    const m = line.match(/^\s+\[[\w-]+\] › (?:tests\/app-e2e\/)?([\w./-]+\.spec\.mjs):(\d+)(?::\d+)?/);
    if (m) { out.add(`${m[1]}:${m[2]}`); continue; }
    inFailed = false;
  }
  return [...out].sort();
}

// latest: main에서 가장 최근에 끝난 push·schedule 실행. run: 이번에 끝난 실행. openIssue: 열린 'main 시험 깨짐' 이슈 번호(없으면 0).
export function decide({run, latest, openIssue}) {
  if (!run || run.head_branch !== 'main' || !EVENTS.has(run.event)) return 'skip';
  if (!latest || latest.id !== run.id) return 'skip';
  if (run.conclusion === 'failure') return openIssue ? 'comment' : 'open';
  if (run.conclusion === 'success') return openIssue ? 'close' : 'skip';
  return 'skip'; // cancelled·skipped 등은 상태를 바꾸지 않는다
}

export function failureBody({run, specs}) {
  const lines = [
    `main 전체 화면 시험이 실패했습니다. 고칠 때까지 커맨드센터는 다른 앱 PR merge를 멈춥니다(AGENTS.md 9절).`,
    '',
    `- 실행: #${run.run_number} (${run.html_url})`,
    `- SHA: \`${String(run.head_sha).slice(0, 12)}\``,
    `- 실패한 시험: ${specs.length ? specs.map(s => `\`${s}\``).join(', ') : '읽지 못함(실행 화면에서 확인)'}`,
  ];
  return lines.join('\n') + FOOTER;
}

export function greenBody({run}) {
  return [`main 전체 화면 시험이 다시 통과했습니다. 이슈를 닫습니다.`, '', `- 실행: #${run.run_number} (${run.html_url})`, `- SHA: \`${String(run.head_sha).slice(0, 12)}\``].join('\n') + FOOTER;
}

function gh(args, input) {
  return execFileSync('gh', ['api', ...args], {encoding: 'utf8', input, maxBuffer: 256 << 20});
}
const json = args => JSON.parse(gh(args));

function main(argv) {
  const arg = name => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : ''; };
  const repo = arg('--repo') || process.env.GITHUB_REPOSITORY;
  const runId = arg('--run');
  const dry = argv.includes('--dry-run');
  if (!repo || !/^\d+$/.test(runId || '')) throw new Error('usage: main-e2e-watch.mjs --run <run_id> [--repo owner/name] [--dry-run]');
  const run = json([`repos/${repo}/actions/runs/${runId}`]);
  const recent = [];
  for (const event of EVENTS) {
    const page = json([`repos/${repo}/actions/workflows/${WORKFLOW}/runs?branch=main&event=${event}&status=completed&per_page=1`]);
    if (page.workflow_runs?.[0]) recent.push(page.workflow_runs[0]);
  }
  const latest = recent.sort((a, b) => Date.parse(b.run_started_at || b.created_at) - Date.parse(a.run_started_at || a.created_at))[0];
  const issues = json([`repos/${repo}/issues?state=open&per_page=100`]);
  const openIssue = issues.find(i => !i.pull_request && i.title === TITLE)?.number || 0;
  const action = decide({run, latest, openIssue});
  console.log(`run=${run.id} event=${run.event} conclusion=${run.conclusion} latest=${latest?.id ?? '-'} issue=${openIssue || '-'} → ${action}`);
  if (action === 'skip') return;
  if (action === 'close') {
    const body = greenBody({run});
    if (dry) { console.log(body); return; }
    gh(['-X', 'POST', `repos/${repo}/issues/${openIssue}/comments`, '-F', 'body=@-'], body);
    gh(['-X', 'PATCH', `repos/${repo}/issues/${openIssue}`, '-f', 'state=closed', '-f', 'state_reason=completed']);
    return;
  }
  const jobs = json([`repos/${repo}/actions/runs/${run.id}/jobs?filter=latest&per_page=100`]).jobs || [];
  const specs = new Set();
  for (const job of jobs.filter(j => j.conclusion === 'failure')) {
    try { for (const s of failedSpecsFromLog(gh([`repos/${repo}/actions/jobs/${job.id}/logs`]))) specs.add(s); }
    catch { /* 로그를 못 읽어도 이슈는 연다 */ }
  }
  const body = failureBody({run, specs: [...specs].sort()});
  if (dry) { console.log(body); return; }
  if (action === 'comment') gh(['-X', 'POST', `repos/${repo}/issues/${openIssue}/comments`, '-F', 'body=@-'], body);
  else gh(['-X', 'POST', `repos/${repo}/issues`, '-f', `title=${TITLE}`, '-F', 'body=@-'], body);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
