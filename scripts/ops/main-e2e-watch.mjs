#!/usr/bin/env node
// main 시험 깨짐 바로 알림 (TEST-시험선택구멍 ②, 2026-11-27 사용자 결정: main 깨짐을 사람이 점검하다 80분 늦게 알았다).
// main의 'App browser E2E check'(push·매일 정기 실행)가 끝날 때마다 .github/workflows/main-e2e-watch.yml이 부른다.
//   - 실패: 'main 시험 깨짐' 이슈를 열거나(이미 열려 있으면 댓글만) 실행 번호·SHA·실패한 시험 위치(파일:줄)만 적는다.
//   - 성공: 열린 'main 시험 깨짐' 이슈에 초록 댓글을 달고 닫는다.
//   - 뒤늦게 끝난 옛 실행(더 새 실행이 이미 끝남)은 아무것도 하지 않는다(순서가 뒤집혀 틀린 상태로 열고 닫지 않게).
// 읽기는 GitHub API GET, 쓰기는 이 저장소 이슈 하나뿐. 비밀값 없음(workflow의 기본 토큰). 시험 제목·오류 글은 옮기지 않는다
// (공개 저장소, 위치 file:line만).
//
//   node scripts/ops/main-e2e-watch.mjs --run <run_id> [--repo owner/name] [--dry]
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

export const ISSUE_TITLE = 'main 시험 깨짐';
export const E2E_WORKFLOW = 'app-e2e-check.yml';
export const WATCHED_EVENTS = ['push', 'schedule'];
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n';

const stripTime = line => line.replace(/^\d{4}-\d\d-\d\dT[\d:.]+Z\s?/, '').replace(/\x1b\[[0-9;]*[A-Za-z]/g, '');
const SPEC_AT = /tests\/app-e2e\/[\w.\-/]+\.spec\.mjs:\d+(?::\d+)?/;

// Playwright line 보고 끝의 'N failed' 묶음에서 실패한 시험 위치(파일:줄:칸)만 뽑는다.
export function failedSpecs(logText) {
  const out = new Set();
  let inFailed = false;
  for (const raw of String(logText).split('\n')) {
    const line = stripTime(raw);
    if (/^\s+\d+ failed\s*$/.test(line)) { inFailed = true; continue; }
    if (!inFailed) continue;
    const at = /^\s{4}\[[\w-]+\] › /.test(line) && line.match(SPEC_AT);
    if (at) { out.add(at[0]); continue; }
    if (/^\s+\d+ (passed|skipped|flaky|did not run|interrupted)\b/.test(line) || /^##\[/.test(line)) inFailed = false;
  }
  return [...out].sort();
}

// 이 실행으로 무엇을 할지. runs: 같은 workflow의 main 실행 목록(API 그대로), run: 이번 실행, openIssue: 열린 이슈 번호|null.
export function decide({run, runs, openIssue}) {
  if (run.head_branch !== 'main' || !WATCHED_EVENTS.includes(run.event)) return {action: 'none', why: 'main push·정기 실행이 아님'};
  if (!['success', 'failure'].includes(run.conclusion)) return {action: 'none', why: `결과 ${run.conclusion}`};
  const newer = runs.find(r => r.id !== run.id && r.head_branch === 'main' && WATCHED_EVENTS.includes(r.event)
    && ['success', 'failure'].includes(r.conclusion) && Date.parse(r.created_at) > Date.parse(run.created_at));
  if (newer) return {action: 'none', why: `더 새 실행 ${newer.id}이 이미 끝남`};
  if (run.conclusion === 'failure') return {action: openIssue ? 'comment' : 'open', issue: openIssue};
  return openIssue ? {action: 'close', issue: openIssue} : {action: 'none', why: '초록, 열린 이슈 없음'};
}

export function failureBody({run, failed, jobs}) {
  const lines = [
    `main 브라우저 E2E가 깨졌습니다. 이 이슈가 열려 있는 동안 커맨드센터는 앱 PR merge를 멈추고 이것부터 고칩니다(AGENTS.md 9절).`,
    '',
    `- 실행: [#${run.run_number}](${run.html_url}) (${run.event})`,
    `- SHA: \`${run.head_sha}\``,
  ];
  if (failed.length) lines.push('- 실패한 시험:', ...failed.map(f => `  - \`${f}\``));
  else lines.push(`- 실패한 job: ${jobs.length ? jobs.map(j => `\`${j}\``).join(', ') : '(목록을 읽지 못함 — 실행 화면에서 확인)'}`);
  return lines.join('\n') + FOOTER;
}

export function successBody({run}) {
  return `main 브라우저 E2E가 다시 초록입니다: [#${run.run_number}](${run.html_url}), SHA \`${run.head_sha}\`. 이슈를 닫습니다.` + FOOTER;
}

const gh = (args, input) => execFileSync('gh', ['api', ...args], {encoding: 'utf8', input, maxBuffer: 64 * 1024 * 1024});
const ghJson = args => JSON.parse(gh(args));

function main(argv) {
  const opt = {repo: process.env.GITHUB_REPOSITORY || 'mj880616/work', dry: false};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--run') opt.run = argv[++i];
    else if (argv[i] === '--repo') opt.repo = argv[++i];
    else if (argv[i] === '--dry') opt.dry = true;
  }
  if (!/^\d+$/.test(String(opt.run || ''))) throw new Error('usage: main-e2e-watch.mjs --run <run_id> [--repo owner/name] [--dry]');
  if (!/^[\w.-]+\/[\w.-]+$/.test(opt.repo)) throw new Error('bad --repo');
  const run = ghJson([`repos/${opt.repo}/actions/runs/${opt.run}`]);
  const runs = ghJson([`repos/${opt.repo}/actions/workflows/${E2E_WORKFLOW}/runs?branch=main&status=completed&per_page=30`]).workflow_runs || [];
  const open = ghJson([`repos/${opt.repo}/issues?state=open&per_page=100`]).find(i => !i.pull_request && i.title === ISSUE_TITLE);
  const plan = decide({run, runs, openIssue: open ? open.number : null});
  console.log(`run ${run.id} ${run.event} ${run.conclusion} ${run.head_sha.slice(0, 7)} → ${plan.action}${plan.why ? ` (${plan.why})` : ''}`);
  if (plan.action === 'none') return;
  let body;
  if (plan.action === 'close') body = successBody({run});
  else {
    const jobs = (ghJson([`repos/${opt.repo}/actions/runs/${run.id}/jobs?per_page=100`]).jobs || []).filter(j => j.conclusion === 'failure');
    const failed = new Set();
    for (const job of jobs.filter(j => /^browser-e2e-shard/.test(j.name))) {
      try { for (const f of failedSpecs(gh([`repos/${opt.repo}/actions/jobs/${job.id}/logs`]))) failed.add(f); } catch { /* 로그를 못 읽으면 job 이름만 */ }
    }
    body = failureBody({run, failed: [...failed].sort(), jobs: jobs.map(j => j.name)});
  }
  console.log(body);
  if (opt.dry) return;
  const payload = JSON.stringify({body});
  if (plan.action === 'open') {
    console.log(JSON.parse(gh([`repos/${opt.repo}/issues`, '-X', 'POST', '--input', '-'], JSON.stringify({title: ISSUE_TITLE, body}))).html_url);
  } else {
    gh([`repos/${opt.repo}/issues/${plan.issue}/comments`, '-X', 'POST', '--input', '-'], payload);
    if (plan.action === 'close') gh([`repos/${opt.repo}/issues/${plan.issue}`, '-X', 'PATCH', '-f', 'state=closed', '-f', 'state_reason=completed']);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
